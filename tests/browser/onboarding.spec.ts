import { expect, test } from "@playwright/test";

test("four onboarding steps lead to three editable goals and explicit replacement confirmation", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/preview");
  await page.getByRole("link", { name: "Set your personal mission" }).click();
  await expect(page.getByRole("heading", { name: "What are you building?" })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect.poll(() => page.getByRole("img", { name: "The Golden Gate Bridge rising through San Francisco's coastal fog at sunrise" }).evaluate((element) => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0)).toBe(true);
  await page.screenshot({ path: "test-results/onboarding-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 320, height: 900 });
  await expect(page.getByRole("navigation", { name: "Main navigation" })).toHaveCount(0);
  expect(await page.getByRole("region", { name: "Set up your mission", exact: true }).evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "at least 10 characters" })).toBeVisible();
  await page.getByRole("textbox", { name: "Your project", exact: true }).fill("A feedback tool for independent game developers.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("textbox", { name: "Your ambitions", exact: true }).fill("Find three potential users and learn from their feedback.");
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Your project", exact: true })).toHaveValue("A feedback tool for independent game developers.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Your ambitions", exact: true })).toHaveValue("Find three potential users and learn from their feedback.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Developer tools", exact: true }).click();
  await expect(page.getByRole("button", { name: "Developer tools", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("textbox", { name: "Your contribution", exact: true }).fill("React prototypes and landing page reviews.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your mission, in three goals." })).toBeVisible();
  await expect(page.getByRole("button", { name: /Use template goals|Suggest new goals|Create my mission/ })).toHaveCount(0);
  await page.getByRole("button", { name: /^Edit goal 1:/ }).press("Enter");
  const goal1 = page.getByRole("group", { name: "Edit goal 1", exact: true });
  const goal2 = page.getByRole("group", { name: "Edit goal 2", exact: true });
  await expect(goal1.getByRole("textbox", { name: "Title", exact: true })).toBeVisible();
  await goal1.getByRole("textbox", { name: "Title", exact: true }).fill("Get four prototype reviews");
  await goal1.getByRole("spinbutton", { name: "How many", exact: true }).fill("4");
  await page.getByRole("button", { name: /^Edit goal 2:/ }).click();
  await expect(goal1.getByRole("textbox", { name: "Title", exact: true })).not.toBeVisible();
  await expect(goal2.getByRole("textbox", { name: "Title", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^Edit goal 2:/ }).click();
  await expect(goal2.getByRole("textbox", { name: "Title", exact: true })).not.toBeVisible();
  for (const width of [1440, 640, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    const panel = page.getByRole("region", { name: "Set up your mission", exact: true });
    expect(await panel.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  }
  await page.getByRole("heading", { name: "Your mission, in three goals." }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/onboarding-mobile.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "test-results/mission-review-desktop.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Confirm my mission", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your mission is set." })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Get four prototype reviews", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit your mission", exact: true }).click();
  await page.getByRole("button", { name: "Edit answers", exact: true }).click();
  for (let step = 0; step < 4; step++) await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "View confirmed mission", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Get four prototype reviews", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
