import { test, expect } from "@playwright/test";

test("preview navigation works on desktop and mobile without granting backend access", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  // Exercise scrolling on a short desktop viewport even when Home fits on taller screens.
  await page.setViewportSize({ width: 1280, height: 600 });
  await page.goto("/preview");
  await expect(page.getByRole("heading", { name: "Make this chapter yours." })).toBeVisible();
  await expect(page.getByText("Workspace preview · Sample cohort.", { exact: false })).toBeVisible();
  const panel = page.getByRole("region", { name: "Workspace content", exact: true });
  const headerTop = (await panel.locator("header").boundingBox())!.y;
  await panel.hover();
  await page.mouse.wheel(0, 600);
  await expect.poll(() => panel.evaluate((element) => element.scrollTop)).toBeGreaterThan(0);
  expect(await page.evaluate(() => window.scrollY)).toBe(0);
  expect((await panel.locator("header").boundingBox())!.y).toBe(headerTop);
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Expand sidebar", exact: true })).toHaveAttribute("aria-expanded", "false");
  await page.keyboard.press("Tab");
  await page.getByRole("link", { name: "Opportunities", exact: true }).focus();
  await expect(page.getByRole("tooltip", { name: "Opportunities", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Command Center", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Command Center" })).toBeVisible();
  await expect.poll(() => panel.evaluate((element) => element.scrollTop)).toBe(0);
  await expect(page.getByRole("button", { name: "New cohort", exact: true })).toBeDisabled();
  await page.reload();
  await expect(page.getByRole("button", { name: "Expand sidebar", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Expand sidebar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Collapse sidebar", exact: true })).toHaveAttribute("aria-expanded", "true");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  await page.getByRole("link", { name: "Community", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your kind of people." })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto("/sign-in");
  await expect(page.getByRole("heading", { name: "Welcome, Hustler." })).toBeVisible();
  const google = page.getByRole("button", { name: /Continue with Google|Google sign-in is not connected yet/ });
  await expect(google).toBeVisible();
  if (await google.innerText() === "Google sign-in is not connected yet") await expect(google).toBeDisabled();
  else await expect(google).toBeEnabled();
  expect(errors).toEqual([]);
});
